import { describe, expect, it } from "vitest";
import type { ApplicationNested, Domain } from "@dokploy/server";
import {
	createRouterConfig,
} from "@dokploy/server/utils/traefik/domain";
import {
	createServiceConfig,
} from "@dokploy/server/utils/traefik/application";
import {
	mapDomainCloudflareStatus,
	type DomainRow,
} from "@dokploy/server/services/cloudflare-saas-service";
import {
	getAuthorizedHostsSync,
	resolveHostValidation,
} from "@dokploy/server/utils/builders/host-validation";
import { buildContainerEnvironmentVariables } from "@dokploy/server/utils/builders";
import { updateViteConfigContent } from "@dokploy/server/utils/builders/vite-config";
import { saveDeploymentPlanSync } from "@dokploy/server/utils/builders/deployment-plan";

const createMockApp = (
	appName: string,
	domainsList: Array<{
		host: string;
		enabled?: boolean;
		verified?: boolean;
		https?: boolean;
		certificateType?: "none" | "letsencrypt" | "custom";
		cfStatus?: string | null;
		cfSslStatus?: string | null;
		uniqueConfigKey?: number;
		port?: number;
	}> = [],
	overrides: Record<string, any> = {},
): ApplicationNested & { domains: any[] } =>
	({
		applicationId: `app-${appName}`,
		appName,
		name: appName,
		buildType: "nixpacks",
		sourceType: "github",
		env: "",
		publishDirectory: null,
		isStaticSpa: false,
		cleanCache: false,
		createEnvFile: true,
		serverId: null,
		applicationStatus: "done",
		domains: domainsList.map((d, idx) => ({
			domainId: `d-${appName}-${idx}`,
			host: d.host,
			enabled: d.enabled !== false,
			verified: d.verified !== false,
			https: d.https !== false,
			certificateType: d.certificateType || "letsencrypt",
			port: d.port || 4173,
			path: "/",
			uniqueConfigKey: d.uniqueConfigKey || idx + 1,
			applicationId: `app-${appName}`,
			cfStatus: d.cfStatus ?? null,
			cfSslStatus: d.cfSslStatus ?? null,
		})),
		environment: {
			env: "",
			name: "production",
			projectId: "proj-1",
			project: {
				organizationId: "org-1",
				name: "Project 1",
				projectId: "proj-1",
				description: "",
				createdAt: new Date().toISOString(),
			},
			environmentId: "env-1",
			createdAt: new Date().toISOString(),
		},
		mounts: [],
		security: [],
		redirects: [],
		ports: [{ targetPort: 4173, publishMode: "ingress", protocol: "tcp" }],
		deployments: [],
		...overrides,
	}) as any;

describe("HatDot Custom Domain Lifecycle, Application Routing, and Cleanup Suite", () => {
	// Scenario 1: Initial deployment routing (autogenerated HatDot subdomain)
	it("Scenario 1: creates correct web and websecure routers on initial deployment for HatDot subdomain", async () => {
		const app = createMockApp("profile-profile-z4lec0", [
			{
				host: "profile-profile-z4lec0.hatdot.cloud",
				enabled: true,
				https: true,
				certificateType: "letsencrypt",
				uniqueConfigKey: 1,
			},
		]);

		const domain = (app.domains as any)[0];
		const webRouter = await createRouterConfig(app, domain, "web");
		const websecureRouter = await createRouterConfig(app, domain, "websecure");
		const service = createServiceConfig(app.appName, domain, app);

		expect(webRouter.rule).toBe("Host(`profile-profile-z4lec0.hatdot.cloud`)");
		expect(webRouter.middlewares).toContain("redirect-to-https");
		expect(websecureRouter.rule).toBe("Host(`profile-profile-z4lec0.hatdot.cloud`)");
		expect(websecureRouter.tls?.certResolver).toBe("letsencrypt");
		expect(service.loadBalancer?.servers?.[0]?.url).toBe("http://profile-profile-z4lec0:4173");
	});

	// Scenario 2: Add custom domain after deployment
	it("Scenario 2: adding custom domain creates Cloudflare Edge TLS router without requesting Let's Encrypt at origin", async () => {
		const app = createMockApp("profile-profile-z4lec0", [
			{
				host: "profile-profile-z4lec0.hatdot.cloud",
				enabled: true,
				https: true,
				certificateType: "letsencrypt",
				uniqueConfigKey: 1,
			},
			{
				host: "luxeenet.com",
				enabled: true,
				https: true,
				certificateType: "none",
				cfStatus: "active",
				cfSslStatus: "active",
				uniqueConfigKey: 2,
			},
		]);

		const cfDomain = (app.domains as any)[1];
		const websecureRouter = await createRouterConfig(app, cfDomain, "websecure");

		// Crucial: Traefik must terminate TLS with default certificate ({}) and NOT certResolver: letsencrypt
		expect(websecureRouter.rule).toBe("Host(`luxeenet.com`)");
		expect(websecureRouter.tls).toEqual({});
		expect(websecureRouter.tls?.certResolver).toBeUndefined();

		// Runtime environment should contain both hostnames
		const envs = buildContainerEnvironmentVariables(app);
		const viteEnv = envs.find((e) => e.startsWith("__VITE_ADDITIONAL_SERVER_ALLOWED_HOSTS="));
		expect(viteEnv).toBeDefined();
		expect(viteEnv).toContain("luxeenet.com");
		expect(viteEnv).toContain("profile-profile-z4lec0.hatdot.cloud");
	});

	// Scenario 3: Delete custom domain - purges custom router, keeps autogenerated subdomain intact
	it("Scenario 3: deleting custom domain leaves only the autogenerated subdomain in Traefik config", async () => {
		// Before deletion: 2 domains
		const appBefore = createMockApp("profile-profile-z4lec0", [
			{ host: "profile-profile-z4lec0.hatdot.cloud", enabled: true, uniqueConfigKey: 1 },
			{ host: "luxeenet.com", enabled: true, uniqueConfigKey: 2 },
		]);
		expect(getAuthorizedHostsSync(appBefore)).toContain("luxeenet.com");

		// After deletion: only autogenerated subdomain remains
		const appAfter = createMockApp("profile-profile-z4lec0", [
			{ host: "profile-profile-z4lec0.hatdot.cloud", enabled: true, uniqueConfigKey: 1 },
		]);

		const hostsAfter = getAuthorizedHostsSync(appAfter);
		expect(hostsAfter).not.toContain("luxeenet.com");
		expect(hostsAfter).toContain("profile-profile-z4lec0.hatdot.cloud");

		// Allowed hosts env updated
		const envs = buildContainerEnvironmentVariables(appAfter);
		const viteEnv = envs.find((e) => e.startsWith("__VITE_ADDITIONAL_SERVER_ALLOWED_HOSTS="));
		expect(viteEnv).not.toContain("luxeenet.com");
		expect(viteEnv).toContain("profile-profile-z4lec0.hatdot.cloud");
	});

	// Scenario 4: Delete autogenerated domain - custom domain remains active, app is preserved
	it("Scenario 4: deleting autogenerated domain leaves only the custom domain, preserving the application", async () => {
		const appAfter = createMockApp("profile-profile-z4lec0", [
			{
				host: "luxeenet.com",
				enabled: true,
				https: true,
				certificateType: "none",
				uniqueConfigKey: 2,
			},
		]);

		// Application must not be destroyed or corrupted
		expect(appAfter.applicationId).toBe("app-profile-profile-z4lec0");
		expect(appAfter.domains.length).toBe(1);
		expect(appAfter.domains[0]?.host).toBe("luxeenet.com");

		const router = await createRouterConfig(appAfter, appAfter.domains[0] as any, "websecure");
		expect(router.rule).toBe("Host(`luxeenet.com`)");
	});

	// Scenario 5: Multiple domains routing and selective removal
	it("Scenario 5: supports 3 attached domains and selective deletion of 1 domain", () => {
		const appWith3 = createMockApp("multi-domain-service", [
			{ host: "multi-domain-service.hatdot.cloud", enabled: true },
			{ host: "shop.example.com", enabled: true },
			{ host: "blog.example.com", enabled: true },
		]);

		const hosts3 = getAuthorizedHostsSync(appWith3);
		expect(hosts3).toContain("shop.example.com");
		expect(hosts3).toContain("blog.example.com");
		expect(hosts3).toContain("multi-domain-service.hatdot.cloud");

		// Selectively remove shop.example.com
		const appWith2 = createMockApp("multi-domain-service", [
			{ host: "multi-domain-service.hatdot.cloud", enabled: true },
			{ host: "blog.example.com", enabled: true },
		]);

		const hosts2 = getAuthorizedHostsSync(appWith2);
		expect(hosts2).not.toContain("shop.example.com");
		expect(hosts2).toContain("blog.example.com");
		expect(hosts2).toContain("multi-domain-service.hatdot.cloud");
	});

	// Scenario 6: Service restart / reconciliation restores clean routing
	it("Scenario 6: vite.config.js dynamically resolves process.env.__VITE_ADDITIONAL_SERVER_ALLOWED_HOSTS across container restarts", () => {
		const originalViteConfig = `
import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';

export default defineConfig({
  plugins: [react()],
});
`;
		const updated = updateViteConfigContent(originalViteConfig, [
			"initial.hatdot.cloud",
		]);

		expect(updated.modified).toBe(true);
		expect(updated.content).toContain("__VITE_ADDITIONAL_SERVER_ALLOWED_HOSTS");
		expect(updated.content).toContain('"initial.hatdot.cloud"');
	});

	// Scenario 7: Failed or pending Cloudflare provisioning separates SSL from Routing
	it("Scenario 7: separates edge SSL status from routing and website ready states", () => {
		const pendingDomain: DomainRow = {
			domainId: "dom-1",
			host: "unverified.com",
			https: false,
			certificateType: "none",
			port: 3000,
			enabled: true,
			cfHostnameId: "cf-123",
			cfStatus: "pending",
			cfSslStatus: "initializing",
			cfVerificationErrors: [],
			cfOwnershipVerification: { name: "_cf-custom-hostname.unverified.com", value: "abc" },
			cfSslValidationRecords: null,
			cfSslCertificates: null,
			cfLastSyncAt: null,
			cfLastError: null,
			cfCustomOrigin: null,
			applicationId: "app-1",
			composeId: null,
			previewDeploymentId: null,
			createdAt: new Date().toISOString(),
			customCertResolver: null,
			customEntrypoint: null,
			forwardAuthEnabled: false,
			internalPath: "/",
			isPrimary: false,
			middlewares: [],
			path: "/",
			serviceName: null,
			stripPath: false,
			uniqueConfigKey: 1,
			domainType: "application",
		};

		const pendingStatus = mapDomainCloudflareStatus(pendingDomain, "cname.hatdot.cloud");
		expect(pendingStatus.isSslActive).toBe(false);
		expect(pendingStatus.isWebsiteReady).toBe(false);
		expect(pendingStatus.stageName).toBe("Verifying domain ownership");

		// Now simulate fully active
		const activeDomain: DomainRow = {
			...pendingDomain,
			https: true,
			cfStatus: "active",
			cfSslStatus: "active",
		};

		const activeStatus = mapDomainCloudflareStatus(activeDomain, "cname.hatdot.cloud");
		expect(activeStatus.isSslActive).toBe(true);
		expect(activeStatus.isRoutingActive).toBe(true);
		expect(activeStatus.isWebsiteReady).toBe(true);
		expect(activeStatus.stageName).toBe("Active — HTTPS ready");
	});

	// Scenario 8: Host validation and framework resolution across various stacks
	it("Scenario 8: host validation works seamlessly for Django (ALLOWED_HOSTS) and static sites", () => {
		const djangoPlan = resolveHostValidation({
			framework: "Django",
			language: "Python",
			runsViteServer: false,
			port: 8000,
			command: "gunicorn myproject.wsgi:application --bind 0.0.0.0:8000",
			hosts: ["luxeenet.com", "myapp.hatdot.cloud"],
		});

		expect(djangoPlan.mechanism).toBe("diagnostic-only");
		expect(djangoPlan.hosts).toContain("luxeenet.com");
		expect(djangoPlan.remediation).toContain("DJANGO_ALLOWED_HOSTS");

		const staticPlan = resolveHostValidation({
			framework: "Static HTML",
			language: "HTML",
			runsViteServer: false,
			port: 80,
			command: null,
			hosts: ["luxeenet.com"],
		});

		expect(staticPlan.mechanism).toBe("none");
		expect(staticPlan.hosts).toContain("luxeenet.com");
	});

	// Scenario 9: Multi-domain disabled flag removes host from active routing
	it("Scenario 9: disabled domain is immediately excluded from authorized hosts and reverse-proxy routing", () => {
		const app = createMockApp("app-toggle", [
			{ host: "active.example.com", enabled: true },
			{ host: "disabled.example.com", enabled: false },
		]);

		const hosts = getAuthorizedHostsSync(app);
		expect(hosts).toContain("active.example.com");
		expect(hosts).not.toContain("disabled.example.com");
	});
});
