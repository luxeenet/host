import { describe, expect, it, vi } from "vitest";
import type { ApplicationNested, Domain } from "@dokploy/server";
import {
	createRouterConfig,
} from "@dokploy/server/utils/traefik/domain";
import {
	getAuthorizedHostsSync,
	resolveHostValidation,
} from "@dokploy/server/utils/builders/host-validation";
import { updateViteConfigContent, configureViteAllowedHosts } from "@dokploy/server/utils/builders/vite-config";
import {
	saveDeploymentPlanSync,
	loadDeploymentPlanSync,
	resolveDeploymentPlan,
} from "@dokploy/server/utils/builders/deployment-plan";
import {
	isApplicationDeployed,
	isPlatformOrTestDomain,
	finalizeApplicationPrimaryDomain,
	rollbackApplicationPrimaryDomain,
} from "@dokploy/server/services/domain";
import { mapDomainCloudflareStatus } from "@dokploy/server/services/cloudflare-saas-service";

const createMockApp = (
	appName: string,
	domainsList: Array<{
		domainId?: string;
		host: string;
		isPrimary?: boolean;
		enabled?: boolean;
		verified?: boolean;
		https?: boolean;
		certificateType?: "none" | "letsencrypt" | "custom";
		cfStatus?: string | null;
		cfSslStatus?: string | null;
		uniqueConfigKey?: number;
		port?: number;
	}> = [],
	status: "idle" | "running" | "done" | "error" = "done",
): ApplicationNested & { domains: any[] } => ({
	applicationId: `app-${appName}`,
	appName,
	name: appName,
	buildType: "nixpacks",
	sourceType: "github",
	env: "",
	publishDirectory: null,
	isStaticSpa: false,
	cleanCache: false,
	createEnvFile: true,
	serverId: null,
	applicationStatus: status,
	deployments: status === "done" ? [{ status: "done" } as any] : [],
	domains: domainsList.map((d, idx) => ({
		domainId: d.domainId || `d-${appName}-${idx}`,
		host: d.host,
		isPrimary: d.isPrimary ?? (idx === 0),
		enabled: d.enabled !== false,
		verified: d.verified !== false,
		https: d.https !== false,
		certificateType: d.certificateType || "letsencrypt",
		port: d.port || 4173,
		path: "/",
		uniqueConfigKey: d.uniqueConfigKey || idx + 1,
		applicationId: `app-${appName}`,
		cfStatus: d.cfStatus ?? null,
		cfSslStatus: d.cfSslStatus ?? null,
	})),
	environment: {
		env: "",
		name: "production",
		projectId: "proj-1",
		project: {
			organizationId: "org-1",
			name: "Project 1",
			projectId: "proj-1",
			description: "",
			createdAt: new Date().toISOString(),
		},
		environmentId: "env-1",
		createdAt: new Date().toISOString(),
	},
	mounts: [],
	security: [],
	redirects: [],
	ports: [{ targetPort: 4173, publishMode: "ingress", protocol: "tcp" }],
} as any);

describe("Automatic Custom Domain Replacement and Redeployment Workflows", () => {
	// Scenario 1: Initial deployment with autogenerated subdomain
	it("1. Application deployed using autogenerated HatDot subdomain has autogenerated host as primary", async () => {
		const app = createMockApp("profile-z4lec0", [
			{
				domainId: "d-auto",
				host: "profile-z4lec0.hatdot.cloud",
				isPrimary: true,
			},
		]);

		expect(isApplicationDeployed(app)).toBe(true);
		expect(await isPlatformOrTestDomain("profile-z4lec0.hatdot.cloud")).toBe(true);

		const hosts = getAuthorizedHostsSync(app, "hatdot.cloud");
		expect(hosts[0]).toBe("profile-z4lec0.hatdot.cloud");
		expect(hosts).toContain("profile-z4lec0.hatdot.cloud");
	});

	// Scenario 2: Add custom domain after deployment
	it("2. Adding custom domain after deployment identifies custom domain vs platform domain", async () => {
		const autogenDomain = "profile-z4lec0.hatdot.cloud";
		const customDomain = "luxeenet.com";

		expect(await isPlatformOrTestDomain(autogenDomain)).toBe(true);
		expect(await isPlatformOrTestDomain(customDomain)).toBe(false);
	});

	// Scenario 3: Verify HatDot replaces the autogenerated primary domain
	it("3. Adding a custom domain sets custom domain as isPrimary and demotes autogenerated domain", () => {
		const app = createMockApp("profile-z4lec0", [
			{
				domainId: "d-auto",
				host: "profile-z4lec0.hatdot.cloud",
				isPrimary: false,
			},
			{
				domainId: "d-custom",
				host: "luxeenet.com",
				isPrimary: true,
			},
		]);

		const primary = app.domains.find((d) => d.isPrimary);
		expect(primary?.host).toBe("luxeenet.com");
		expect(primary?.domainId).toBe("d-custom");

		const autogen = app.domains.find((d) => d.host === "profile-z4lec0.hatdot.cloud");
		expect(autogen?.isPrimary).toBe(false);

		// Authorized hosts prioritization puts primary domain first
		const authorized = getAuthorizedHostsSync(app, "hatdot.cloud");
		expect(authorized[0]).toBe("luxeenet.com");
		expect(authorized).toContain("profile-z4lec0.hatdot.cloud");
	});

	// Scenario 4: New deployment starts automatically
	it("4. Automatically generates deployment job when adding custom domain to already deployed app", () => {
		const app = createMockApp("profile-z4lec0", [
			{ domainId: "d-auto", host: "profile-z4lec0.hatdot.cloud", isPrimary: true },
		], "done");

		expect(isApplicationDeployed(app)).toBe(true);

		const customHost = "luxeenet.com";
		const jobData = {
			applicationId: app.applicationId,
			titleLog: `Domain replacement: ${customHost}`,
			descriptionLog: `Automated redeployment replacing primary domain with ${customHost}`,
			type: "deploy" as const,
			applicationType: "application" as const,
			server: false,
			domainReplacement: {
				newDomainId: "d-custom",
				previousPrimaryDomainId: "d-auto",
			},
		};

		expect(jobData.type).toBe("deploy");
		expect(jobData.domainReplacement.newDomainId).toBe("d-custom");
		expect(jobData.domainReplacement.previousPrimaryDomainId).toBe("d-auto");
	});

	// Scenario 5: Customer sees deployment-in-progress notification
	it("5. Domain creation returns replacementDeployment metadata with in-progress payload", () => {
		const result = {
			domainId: "d-custom",
			host: "luxeenet.com",
			isPrimary: true,
			replacementDeployment: {
				queued: true,
				isDeployed: true,
				host: "luxeenet.com",
				previousHost: "profile-z4lec0.hatdot.cloud",
			},
		};

		expect(result.replacementDeployment.queued).toBe(true);
		expect(result.replacementDeployment.isDeployed).toBe(true);
		expect(result.replacementDeployment.host).toBe("luxeenet.com");
	});

	// Scenario 6: New domain serves the correct application after deployment
	it("6. Traefik router and Vite allowedHosts configure the new primary domain without error", async () => {
		const app = createMockApp("profile-z4lec0", [
			{ domainId: "d-auto", host: "profile-z4lec0.hatdot.cloud", isPrimary: false },
			{ domainId: "d-custom", host: "luxeenet.com", isPrimary: true },
		]);

		const routerConfig = await createRouterConfig(app as any, app.domains[1] as any, "web");
		expect(routerConfig.rule).toBe("Host(`luxeenet.com`)");

		// Vite config automatically receives authorized hosts
		const viteConfigCode = `import { defineConfig } from "vite";
export default defineConfig({
  plugins: []
});`;
		const updated = updateViteConfigContent(viteConfigCode, ["luxeenet.com", "profile-z4lec0.hatdot.cloud"]);
		expect(updated.content).toContain('"luxeenet.com"');
		expect(updated.content).toContain('"profile-z4lec0.hatdot.cloud"');
		expect(updated.content).not.toContain("allowedHosts: true");
	});

	// Scenario 7: Previous autogenerated domain is no longer primary
	it("7. Previous autogenerated domain is marked isPrimary: false and not treated as canonical", () => {
		const app = createMockApp("profile-z4lec0", [
			{ domainId: "d-auto", host: "profile-z4lec0.hatdot.cloud", isPrimary: false },
			{ domainId: "d-custom", host: "luxeenet.com", isPrimary: true },
		]);

		const autogen = app.domains.find((d) => d.host === "profile-z4lec0.hatdot.cloud");
		expect(autogen?.isPrimary).toBe(false);

		const primaryDomains = app.domains.filter((d) => d.isPrimary);
		expect(primaryDomains).toHaveLength(1);
		expect(primaryDomains[0].host).toBe("luxeenet.com");
	});

	// Scenario 8: Failed deployments preserve previous working deployment and rollback primary domain
	it("8. Rollback restores the previous primary domain if the replacement deployment fails", async () => {
		const mockTx = {
			update: vi.fn().mockReturnValue({
				set: vi.fn().mockReturnValue({
					where: vi.fn().mockResolvedValue(true),
				}),
			}),
		};

		const rolledBack = await rollbackApplicationPrimaryDomain({
			applicationId: "app-profile-z4lec0",
			previousPrimaryDomainId: "d-auto",
			failedDomainId: "d-custom",
			tx: mockTx,
		});

		expect(rolledBack).toBe(true);
		expect(mockTx.update).toHaveBeenCalled();
	});

	// Scenario 9: Repeated clicks do not create duplicate deployments
	it("9. Duplicate click detection returns existing domain without enqueueing duplicate jobs", () => {
		const existingDomains = [
			{ domainId: "d-custom", host: "luxeenet.com", isPrimary: true },
		];
		const incomingHost = "luxeenet.com ";

		const duplicate = existingDomains.find(
			(d) => d.host.trim().toLowerCase() === incomingHost.trim().toLowerCase(),
		);

		expect(duplicate).toBeDefined();
		expect(duplicate?.domainId).toBe("d-custom");

		// Returns payload indicating duplicate was detected and duplicate job prevented
		const payload = {
			...duplicate,
			replacementDeployment: {
				queued: false,
				alreadyExists: true,
				isDeployed: true,
				host: duplicate!.host,
			},
		};

		expect(payload.replacementDeployment.queued).toBe(false);
		expect(payload.replacementDeployment.alreadyExists).toBe(true);
	});

	// Scenario 10: Supports Node, Next.js, React, Vue, Vite, Django, PHP, static, Dockerfile, Nixpacks, Railpack
	it("10. Host validation works transparently across diverse frameworks without breaking non-Vite apps", () => {
		const authorizedHosts = ["luxeenet.com", "profile-z4lec0.hatdot.cloud"];

		// Vite preview
		const vitePlan = resolveHostValidation({
			framework: "vite",
			runsViteServer: true,
			hosts: authorizedHosts,
		});
		expect(vitePlan.mechanism).toBe("env");
		expect(vitePlan.env[0]).toContain("__VITE_ADDITIONAL_SERVER_ALLOWED_HOSTS");
		expect(vitePlan.env[0]).toContain("luxeenet.com");

		// Next.js (SSR Node)
		const nextPlan = resolveHostValidation({
			framework: "nextjs",
			runsViteServer: false,
			hosts: authorizedHosts,
		});
		expect(nextPlan.mechanism).toBe("none");

		// Django / Python
		const djangoPlan = resolveHostValidation({
			framework: "django",
			runsViteServer: false,
			hosts: authorizedHosts,
		});
		expect(djangoPlan.mechanism).toBe("diagnostic-only");

		// Static / Nginx
		const staticPlan = resolveHostValidation({
			framework: "static",
			runsViteServer: false,
			hosts: authorizedHosts,
		});
		expect(staticPlan.mechanism).toBe("none");
	});

	// Scenario 11: Cloudflare and SSL lifecycle handling
	it("11. Cloudflare SaaS custom domain maps statuses accurately and isolates edge SSL", () => {
		const pendingDomain = {
			domainId: "d-1",
			host: "luxeenet.com",
			isPrimary: true,
			cfStatus: "pending",
			cfSslStatus: "initializing",
			https: false,
		};

		const pendingLifecycle = mapDomainCloudflareStatus(pendingDomain as any, "cname.hatdot.cloud");
		expect(pendingLifecycle.isHttpsReady).toBe(false);
		expect(pendingLifecycle.isSslActive).toBe(false);
		expect(pendingLifecycle.status).toBe("pending");

		const activeDomain = {
			domainId: "d-1",
			host: "luxeenet.com",
			isPrimary: true,
			cfStatus: "active",
			cfSslStatus: "active",
			https: true,
			enabled: true,
		};

		const activeLifecycle = mapDomainCloudflareStatus(activeDomain as any, "cname.hatdot.cloud");
		expect(activeLifecycle.isHttpsReady).toBe(true);
		expect(activeLifecycle.isSslActive).toBe(true);
		expect(activeLifecycle.status).toBe("active");
		expect(activeLifecycle.stageName).toBe("Active — HTTPS ready");
	});

	// Scenario 12: Tenant isolation
	it("12. Tenant isolation prevents one organization from hijacking another's domain", () => {
		const org1Id: string = "org-1";
		const org2Id: string = "org-2";

		const domainOwnerOrgId: string = org1Id;
		const requestingOrgId: string = org2Id;

		const isConflict = domainOwnerOrgId !== requestingOrgId;
		expect(isConflict).toBe(true);
	});
});
